# The compiled model (design §4.5, §4.7): its IR, the tier asked for, and an
# environment holding the external pointer to the lowered code. A saved
# model keeps only the IR (D18): after readRDS() the pointer is nil, and
# the code is generated again on first use.

tier_codes <- c(native = 1L, interp = 2L)

# The tiers zumir reports this session can run: c(native =, interp =).
zupmxode_tiers <- function() {
  .Call(zpx_tiers)
}

resolve_tier <- function(tier, call = NULL) {
  if (!is.character(tier) || length(tier) != 1L || is.na(tier) ||
        !tier %in% c("auto", "native", "interp")) {
    pmx_abort("pmx_ode_error_argument",
              "`tier` must be one of \"auto\", \"native\" or \"interp\".",
              call = call)
  }
  avail <- zupmxode_tiers()
  if (tier == "auto") {
    tier <- if (avail[["native"]]) "native" else if (avail[["interp"]]) "interp" else "none"
  }
  if (tier == "none" || !avail[[tier]]) {
    # D15: where zumir runs no tier, the model cannot run here at all.
    pmx_abort(
      "pmx_ode_error_no_tier",
      paste0(
        if (tier == "none") "No execution tier runs in this session" else
          paste0("The ", tier, " tier does not run in this session"),
        ": zumir::zumir_tier() reports what this system allows."
      ),
      tier = tier, call = call
    )
  }
  tier
}

new_model <- function(ir, tier = "auto") {
  ir_check(ir)
  m <- structure(
    list(ir = ir, tier_request = tier, state = new.env(parent = emptyenv())),
    class = "pmx_ode_model"
  )
  model_lower(m)
  m
}

# Lowers m's IR into m$state. A native generation failure under "auto" falls
# back to the interpreter with a warning (design §8).
model_lower <- function(m, call = NULL) {
  tier <- resolve_tier(m$tier_request, call)
  started <- proc.time()[["elapsed"]]
  res <- .Call(zpx_model_new, m$ir$code, m$ir$consts, tier_codes[[tier]])
  m$state$lowering_seconds <- proc.time()[["elapsed"]] - started
  if (is.list(res) && res$status == "lowering" && tier == "native" &&
        m$tier_request == "auto" && zupmxode_tiers()[["interp"]]) {
    pmx_warn("pmx_ode_warning_tier_fallback",
             paste0("Native code generation failed (", res$message,
                    "); the model runs on the interpreter tier."))
    tier <- "interp"
    res <- .Call(zpx_model_new, m$ir$code, m$ir$consts, tier_codes[[tier]])
  }
  if (is.list(res)) {
    switch(res$status,
      ir = abort_ir(res),
      no_tier = resolve_tier(tier, call),
      api = pmx_abort("pmx_ode_error_lowering",
                      paste0("zumir's C API cannot be loaded: ", res$message, "."),
                      call = call),
      pmx_abort("pmx_ode_error_lowering", paste0(
        "Lowering the model to MIR failed",
        if (res$block >= 0) paste0(" in block `", ir_blocks[res$block + 1L], "`"),
        ": ", if (nzchar(res$message)) res$message else "no message from MIR",
        ". This is a bug in zupmxode or MIR; please report it."
      ), block = if (res$block >= 0) ir_blocks[res$block + 1L] else NA_character_,
      call = call)
    )
  }
  m$state$ptr <- res
  invisible(m)
}

# The model's code, generated again if the model was saved and restored.
model_ptr <- function(m) {
  ptr <- m$state$ptr
  if (is.null(ptr) || !.Call(zpx_model_valid, ptr)) {
    model_lower(m)
    ptr <- m$state$ptr
  }
  ptr
}

# Block `block` of m, once: list(out, work).
model_eval <- function(m, block, t = 0, y = double(), par = double(),
                       work = NULL) {
  if (is.null(work)) work <- double(ir_dims(m$ir)$nwork)
  .Call(zpx_model_eval, model_ptr(m), match(block, ir_blocks) - 1L,
        as.double(t), as.double(y), as.double(par), as.double(work))
}

#' The execution tier of a model
#'
#' A model runs as native code generated by MIR, or on MIR's interpreter
#' where native code cannot be made here; both give the same doubles
#' (design §6.3). `pmx_ode_tier(model)` says which tier `model` runs on;
#' `pmx_ode_tier(model, tier)` returns a copy that runs on `tier`.
#'
#' @param model A model.
#' @param tier `"auto"` (native where it runs, else the interpreter),
#'   `"native"` or `"interp"`.
#' @return The tier, `"native"` or `"interp"`; or, given `tier`, the model
#'   on that tier.
#' @section Errors:
#' `pmx_ode_error_no_tier` when the tier asked for does not run in this
#' session, or when none does: `zumir::zumir_tier()` reports what the system
#' allows.
#' @export
pmx_ode_tier <- function(model, tier) {
  if (!inherits(model, "pmx_ode_model")) {
    pmx_abort("pmx_ode_error_argument", "`model` must be a model.",
              call = sys.call())
  }
  if (missing(tier)) {
    return(names(tier_codes)[.Call(zpx_model_tier, model_ptr(model))])
  }
  resolve_tier(tier, call = sys.call())
  # The copy keeps what the compiler recorded (states, class, options) and
  # gets its own lowered code: model$state is an environment, shared by
  # copies, so it is replaced, never written.
  m <- model
  m$tier_request <- tier
  m$state <- new.env(parent = emptyenv())
  model_lower(m, call = sys.call())
  m
}
